"""# Naive Bayes"""

def custom_penalty_score(y_true, y_pred, labels, cost_matrix):
    """
    Calculates a mean penalty score based on a custom cost matrix.
    The score is normalized by the number of samples to allow
    comparison between different set sizes (e.g., train vs test).
    Lower scores are better.
    """
    from sklearn.metrics import confusion_matrix

    cm = confusion_matrix(y_true, y_pred, labels=labels)
    # Multiply the confusion matrix by the cost matrix element-wise
    weighted_penalties = cm * cost_matrix
    total_penalty = np.sum(weighted_penalties)

    # Normalize by total number of samples
    mean_penalty = total_penalty / len(y_true)

    return mean_penalty, cm

# Define your labels in the specific order they appear in the matrix
labels = ['GA', 'M', 'PG']

# Define your cost matrix (Rows = Actual, Cols = Predicted)
costs = np.array([
    [0, 16, 1],   # Actual GA
    [20, 0, 12],  # Actual M
    [2, 8, 0]     # Actual PG
])

# Note: ensure y_pred is defined from your model before running this
# penalty, cm_result = custom_penalty_score(y_test, y_pred, labels, costs)
# print(f"Mean Custom Penalty Score: {penalty:.4f}")

# Initialize models
alpha = 1.0

xgb_2 = XGBClassifier(random_state=42) # XGB Selected Feature
xgb_3 = XGBClassifier(random_state=42) # XGB Sampled
xgb_4 = XGBClassifier(random_state=42) # XGB Sampled + Selected Feature

# Train XGB models
# Use sample weights for imbalanced data (1 and 2)
xgb_1.fit(X_train, y_train_enc, sample_weight=sample_weights_train)
xgb_2.fit(X_train[significant_features], y_train_enc, sample_weight=sample_weights_train)

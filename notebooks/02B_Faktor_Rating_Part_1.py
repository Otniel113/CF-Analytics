bnb_1 = BernoulliNB(alpha=alpha, class_prior=class_prior) # NB Default
bnb_2 = BernoulliNB(alpha=alpha, class_prior=class_prior) # NB Selected Feature
bnb_3 = BernoulliNB(alpha=alpha) # NB Sampled
bnb_4 = BernoulliNB(alpha=alpha) # NB Sampled + Selected Feature


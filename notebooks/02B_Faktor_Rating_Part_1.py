bnb_4.fit(X_res[significant_features], y_res)

# Scenarios setup for evaluation loop
nb_scenarios = [
    ("NB Default", bnb_1, X_test),
    ("NB Selected Feature", bnb_2, X_test[significant_features]),
    ("NB Sampled", bnb_3, X_test),
    ("NB Sampled + Selected Feature", bnb_4, X_test[significant_features])
]

performance_results = []

